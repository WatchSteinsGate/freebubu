"""Apply the version-guarded Windows debugging patch without assembler dependencies."""
import hashlib,json,pathlib,struct

def patch(data,project):
 plan=json.loads((pathlib.Path(project)/'patcher/native/debug-patch.json').read_text())
 if hashlib.sha256(data).hexdigest()!=plan['input_sha256']:raise ValueError('Unsupported native client: debugging patch checksum mismatch')
 d=bytearray(data);pe=struct.unpack_from('<I',d,0x3c)[0];opt=pe+24;num=struct.unpack_from('<H',d,pe+6)[0];sec=opt+struct.unpack_from('<H',d,pe+20)[0]
 assert sec+(num+2)*40<=struct.unpack_from('<I',d,opt+60)[0]
 align=lambda n,a:(n+a-1)//a*a
 filealign=struct.unpack_from('<I',d,opt+36)[0]
 for item in plan['patches']:
  off=item['offset'];old=bytes.fromhex(item['before']);new=bytes.fromhex(item['after']);assert d[off:off+len(old)]==old;d[off:off+len(old)]=new
 for idx,(name,rva,blob,flags) in enumerate([(b'.nbdbg',plan['code_rva'],bytes.fromhex(plan['code_hex']),0x60000020),(b'.nbimp',plan['data_rva'],bytes.fromhex(plan['imports_hex']),0xc0000040)]):
  offset=align(len(d),filealign);size=align(len(blob),filealign);d+=b'\0'*(offset-len(d));d+=blob+b'\0'*(size-len(blob));header=sec+(num+idx)*40
  struct.pack_into('<8sIIIIIIHHI',d,header,name,len(blob),rva,size,offset,0,0,0,0,flags)
 struct.pack_into('<H',d,pe+6,num+2);struct.pack_into('<I',d,opt+56,plan['data_rva']+0x1000)
 struct.pack_into('<II',d,opt+112+8,plan['data_rva'],plan['import_directory_size'])
 struct.pack_into('<I',d,opt+4,struct.unpack_from('<I',d,opt+4)[0]+align(len(bytes.fromhex(plan['code_hex'])),filealign))
 struct.pack_into('<I',d,opt+8,struct.unpack_from('<I',d,opt+8)[0]+align(len(bytes.fromhex(plan['imports_hex'])),filealign))
 struct.pack_into('<I',d,opt+64,0) # optional PE checksum; resource SHA-256 is regenerated by packaging
 return bytes(d)
if __name__=='__main__':
 import sys
 src,dest=map(pathlib.Path,sys.argv[1:3]);dest.write_bytes(patch(src.read_bytes(),pathlib.Path(__file__).resolve().parents[1]));print('Patched',dest)
